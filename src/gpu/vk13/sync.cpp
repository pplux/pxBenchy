namespace vk13 {

// One row per vkc::Use bit, in bit order. Buffer-only uses have layout UNDEFINED.
static constexpr Sync TABLE[] = {
    // COPY_SRC
    {VK_PIPELINE_STAGE_2_COPY_BIT, VK_ACCESS_2_TRANSFER_READ_BIT, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL},
    // COPY_DST
    {VK_PIPELINE_STAGE_2_COPY_BIT, VK_ACCESS_2_TRANSFER_WRITE_BIT, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL},
    // BLIT_SRC
    {VK_PIPELINE_STAGE_2_BLIT_BIT, VK_ACCESS_2_TRANSFER_READ_BIT, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL},
    // BLIT_DST
    {VK_PIPELINE_STAGE_2_BLIT_BIT, VK_ACCESS_2_TRANSFER_WRITE_BIT, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL},
    // VERTEX_BUFFER
    {VK_PIPELINE_STAGE_2_VERTEX_ATTRIBUTE_INPUT_BIT, VK_ACCESS_2_VERTEX_ATTRIBUTE_READ_BIT, VK_IMAGE_LAYOUT_UNDEFINED},
    // INDEX_BUFFER
    {VK_PIPELINE_STAGE_2_INDEX_INPUT_BIT, VK_ACCESS_2_INDEX_READ_BIT, VK_IMAGE_LAYOUT_UNDEFINED},
    // INDIRECT_BUFFER
    {VK_PIPELINE_STAGE_2_DRAW_INDIRECT_BIT, VK_ACCESS_2_INDIRECT_COMMAND_READ_BIT, VK_IMAGE_LAYOUT_UNDEFINED},
    // UNIFORM_GRAPHICS
    {VK_PIPELINE_STAGE_2_VERTEX_SHADER_BIT | VK_PIPELINE_STAGE_2_FRAGMENT_SHADER_BIT, VK_ACCESS_2_UNIFORM_READ_BIT,
     VK_IMAGE_LAYOUT_UNDEFINED},
    // STORAGE_READ_GRAPHICS
    {VK_PIPELINE_STAGE_2_VERTEX_SHADER_BIT | VK_PIPELINE_STAGE_2_FRAGMENT_SHADER_BIT,
     VK_ACCESS_2_SHADER_STORAGE_READ_BIT, VK_IMAGE_LAYOUT_UNDEFINED},
    // STORAGE_RW_COMPUTE
    {VK_PIPELINE_STAGE_2_COMPUTE_SHADER_BIT, VK_ACCESS_2_SHADER_STORAGE_READ_BIT | VK_ACCESS_2_SHADER_STORAGE_WRITE_BIT,
     VK_IMAGE_LAYOUT_GENERAL},
    // SAMPLED_FRAGMENT
    {VK_PIPELINE_STAGE_2_FRAGMENT_SHADER_BIT, VK_ACCESS_2_SHADER_SAMPLED_READ_BIT,
     VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL},
    // SAMPLED_COMPUTE
    {VK_PIPELINE_STAGE_2_COMPUTE_SHADER_BIT, VK_ACCESS_2_SHADER_SAMPLED_READ_BIT,
     VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL},
    // COLOR_ATTACH_READ
    {VK_PIPELINE_STAGE_2_COLOR_ATTACHMENT_OUTPUT_BIT, VK_ACCESS_2_COLOR_ATTACHMENT_READ_BIT,
     VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL},
    // COLOR_ATTACH_WRITE
    {VK_PIPELINE_STAGE_2_COLOR_ATTACHMENT_OUTPUT_BIT, VK_ACCESS_2_COLOR_ATTACHMENT_WRITE_BIT,
     VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL},
    // DEPTH_ATTACH
    {VK_PIPELINE_STAGE_2_EARLY_FRAGMENT_TESTS_BIT | VK_PIPELINE_STAGE_2_LATE_FRAGMENT_TESTS_BIT,
     VK_ACCESS_2_DEPTH_STENCIL_ATTACHMENT_READ_BIT | VK_ACCESS_2_DEPTH_STENCIL_ATTACHMENT_WRITE_BIT,
     VK_IMAGE_LAYOUT_DEPTH_ATTACHMENT_OPTIMAL},
    // PRESENT
    {VK_PIPELINE_STAGE_2_COLOR_ATTACHMENT_OUTPUT_BIT, VK_ACCESS_2_NONE, VK_IMAGE_LAYOUT_PRESENT_SRC_KHR},
    // HOST_READ
    {VK_PIPELINE_STAGE_2_HOST_BIT, VK_ACCESS_2_HOST_READ_BIT, VK_IMAGE_LAYOUT_UNDEFINED},
    // ACQUIRE_COLOR
    {VK_PIPELINE_STAGE_2_COLOR_ATTACHMENT_OUTPUT_BIT, VK_ACCESS_2_NONE, VK_IMAGE_LAYOUT_UNDEFINED},
    // ACQUIRE_COPY
    {VK_PIPELINE_STAGE_2_COPY_BIT, VK_ACCESS_2_NONE, VK_IMAGE_LAYOUT_UNDEFINED},
};
static_assert(sizeof(TABLE) / sizeof(TABLE[0]) == vkc::USE_COUNT);

Sync sync_of(uint32_t uses) {
  Sync s;
  bool first = true;
  for (; uses; uses &= uses - 1) {
    const Sync& r = TABLE[std::countr_zero(uses)];
    assert(first || r.layout == s.layout);
    s.stage |= r.stage;
    s.access |= r.access;
    s.layout = r.layout;
    first = false;
  }
  return s;
}

} // namespace vk13
